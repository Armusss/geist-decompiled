#!/usr/bin/env python3
"""Write the provisional game units from build/tu_proposal.json into splits.txt (.text only, in address
order next to the already split zlib units) and into configure.py (between the "game units" markers, all
NonMatching). Re-running replaces the previous generated game units. Existing non-game units are kept.

Usage: python3 tools/gen_game_splits.py   (then python3 configure.py && ninja; main.dol must stay OK)"""
import json, os, re

GM = os.environ.get('GM', os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPL = os.path.join(GM, 'config/GITE01/splits.txt')
CFG = os.path.join(GM, 'configure.py')
units = json.load(open(os.path.join(GM, 'build/tu_proposal.json')))

spl = open(SPL).read()
head, body = spl.split('\n\n', 1)
blocks = [b for b in body.strip('\n').split('\n\n') if b.strip()]
blocks = [b for b in blocks if not b.startswith('game/')]          # drop previous generated units


def start_of(block):
    m = re.search(r'\.text\s+start:0x([0-9A-F]+)', block)
    return int(m[1], 16) if m else 1 << 40


existing = [(start_of(b), b) for b in blocks]
taken = [(s, int(re.search(r'end:0x([0-9A-F]+)', b)[1], 16)) for s, b in existing if s < (1 << 40)]


def overlaps(a, b):
    return any(a < e and s < b for s, e in taken)


used = {}
new = []
for a, b, conf, names in units:
    # skip anything already covered by real units (zlib etc.); trim nothing, just leave the gap to dtk
    if overlaps(a, b):
        continue
    name = names.split(',')[0] if names and ',' not in names else ''
    base = os.path.splitext(name)[0] if name else f'u_{a:08X}'
    if base in used:
        base = f'{base}_{a:08X}'
    used[base] = 1
    ext = '.c' if name.endswith('.c') else '.cpp'
    path = f'game/{base}{ext}'
    new.append((a, f'{path}:\n\t.text       start:0x{a:08X} end:0x{b:08X}', path, conf))

allb = sorted(existing + [(a, blk) for a, blk, _, _ in new], key=lambda x: x[0])
open(SPL, 'w').write(head + '\n\n' + '\n\n'.join(b for _, b in allb) + '\n')

cfg = open(CFG).read()
lines = '\n'.join(f'            Object(NonMatching, "{p}"),  # {c}' for _, _, p, c in new)
block = f'''    # ==== game units (generated by tools/gen_game_splits.py; provisional boundaries) ====
    {{
        "lib": "game",
        "mw_version": "GC/1.3.2",
        "cflags": cflags_game,
        "progress_category": "game",
        "objects": [
{lines}
        ],
    }},
    # ==== end game units ===='''
if '# ==== game units' in cfg:
    cfg = re.sub(r'    # ==== game units.*?# ==== end game units ====', lambda m: block, cfg, flags=re.S)
else:
    cfg = cfg.replace('    # ==== helper-msl: MSL_C', block + '\n    # ==== helper-msl: MSL_C', 1)
if 'cflags_game =' not in cfg:
    cfg = cfg.replace('# REL flags', '''# Game code (G1): GC/1.3.x, C++; -O4,p, -fp_contract on (from cflags_base). Unsettled: stmw, deferred inlining.
cflags_game = [
    *cflags_base,
    "-lang=c++",
    "-str reuse,pool,readonly",
]

# REL flags''', 1)
open(CFG, 'w').write(cfg)
print('game units written:', len(new))
